import type { Task, MonthlyCosts, MonthlyReport, MonthlyReportOrder } from '../types';

export const POLISH_MONTH_NAMES = [
  'Styczeń', 'Luty', 'Marzec', 'Kwiecień', 'Maj', 'Czerwiec',
  'Lipiec', 'Sierpień', 'Wrzesień', 'Październik', 'Listopad', 'Grudzień'
];

export const STORAGE_KEY_REPORTS = 'taskhub_monthly_reports';

/**
 * Helper: format Date to local YYYY-MM-DD
 */
export const toLocalDateStr = (d: Date): string => {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
};

/**
 * Helper to determine task's primary date for monthly cashflow
 */
export const getTaskMonthlyDate = (t: Task): string => {
  if (t.status === 'paid' && t.completedAt) {
    try {
      const d = new Date(t.completedAt);
      if (!isNaN(d.getTime())) return toLocalDateStr(d);
    } catch {}
  }
  if (t.dueDate) {
    if (/^\d{4}-\d{2}-\d{2}$/.test(t.dueDate)) return t.dueDate;
    try {
      const d = new Date(t.dueDate);
      if (!isNaN(d.getTime())) return toLocalDateStr(d);
    } catch {}
  }
  if (t.completedAt) {
    try {
      const d = new Date(t.completedAt);
      if (!isNaN(d.getTime())) return toLocalDateStr(d);
    } catch {}
  }
  if (t.startDate) {
    if (/^\d{4}-\d{2}-\d{2}$/.test(t.startDate)) return t.startDate;
    try {
      const d = new Date(t.startDate);
      if (!isNaN(d.getTime())) return toLocalDateStr(d);
    } catch {}
  }
  if (t.createdAt) {
    try {
      const d = new Date(t.createdAt);
      if (!isNaN(d.getTime())) return toLocalDateStr(d);
    } catch {}
    if (t.createdAt.length >= 10) return t.createdAt.slice(0, 10);
  }
  return '';
};

/**
 * Filter tasks belonging to a specific month (1-12) and year
 */
export const filterTasksForMonth = (tasks: Task[], year: number, month: number): Task[] => {
  const ym = `${year}-${String(month).padStart(2, '0')}`;
  return tasks.filter((t) => {
    if (t.category === 'personal') return false;
    const cashDate = getTaskMonthlyDate(t);
    if (cashDate && cashDate.startsWith(ym)) return true;
    const createdYm = t.createdAt ? t.createdAt.slice(0, 7) : '';
    const dueYm = t.dueDate ? t.dueDate.slice(0, 7) : '';
    const startYm = t.startDate ? t.startDate.slice(0, 7) : '';
    return createdYm === ym || dueYm === ym || startYm === ym;
  });
};

/**
 * Generate a complete, high-precision Monthly Report object
 */
export const generateMonthlyReport = (
  year: number,
  month: number, // 1 - 12
  tasks: Task[],
  costs: MonthlyCosts,
  isAutoGenerated = true
): MonthlyReport => {
  const monthName = `${POLISH_MONTH_NAMES[month - 1]} ${year}`;
  const daysInMonth = new Date(year, month, 0).getDate();
  const period = `01.${String(month).padStart(2, '0')}.${year} – ${String(daysInMonth).padStart(2, '0')}.${String(month).padStart(2, '0')}.${year}`;
  const id = `report-${year}-${String(month).padStart(2, '0')}`;

  const monthTasks = filterTasksForMonth(tasks, year, month);

  const paidTasks = monthTasks.filter((t) => t.status === 'paid');
  const paidRevenue = paidTasks.reduce((sum, t) => sum + (Number(t.price) || 0), 0);

  const pendingTasks = monthTasks.filter((t) => t.status === 'in_progress' || t.status === 'todo');
  const pendingRevenue = pendingTasks.reduce((sum, t) => sum + (Number(t.price) || 0), 0);

  const doneTasks = monthTasks.filter((t) => t.status === 'done');

  const totalValue = paidRevenue + pendingRevenue;
  const zus = Number(costs.zus) || 0;
  const tax = Number(costs.tax) || 0;
  const totalCosts = zus + tax;
  const netProfit = paidRevenue - totalCosts;
  const profitMargin = paidRevenue > 0 ? Math.round((netProfit / paidRevenue) * 100) : 0;

  const totalTasksCount = monthTasks.length;
  const completedCount = paidTasks.length + doneTasks.length;
  const completionRate = totalTasksCount > 0 ? Math.round((completedCount / totalTasksCount) * 100) : 0;

  const orders: MonthlyReportOrder[] = monthTasks.map((t) => ({
    id: t.id,
    title: t.title,
    price: Number(t.price) || 0,
    status: t.status,
    category: t.category,
    dueDate: t.dueDate,
    completedAt: t.completedAt,
  }));

  // Auto timestamp: if auto-generated for the last day, stamp at 23:50
  const now = new Date();
  let generatedAt = now.toISOString();
  if (isAutoGenerated) {
    const reportDate = new Date(year, month - 1, daysInMonth, 23, 50, 0);
    generatedAt = reportDate.toISOString();
  }

  const executiveNotes = `Miesięczny raport finansowo-operacyjny JC Studio za okres ${period}. ${
    isAutoGenerated
      ? 'Wygenerowany automatycznie w ostatni dzień miesiąca o godz. 23:50.'
      : 'Wygenerowany na żądanie (podgląd bieżącego okresu).'
  } Zrealizowano przychód ${paidRevenue.toLocaleString('pl-PL')} zł, zysk netto po kosztach stałych (ZUS/podatek ${totalCosts.toLocaleString('pl-PL')} zł) wyniósł ${netProfit.toLocaleString('pl-PL')} zł.`;

  return {
    id,
    year,
    month,
    monthName,
    period,
    generatedAt,
    isAutoGenerated,
    financials: {
      paidRevenue,
      pendingRevenue,
      totalValue,
      zus,
      tax,
      totalCosts,
      netProfit,
      profitMargin,
    },
    metrics: {
      totalTasks: totalTasksCount,
      paidCount: paidTasks.length,
      doneCount: doneTasks.length,
      inProgressCount: pendingTasks.length,
      completionRate,
    },
    orders,
    executiveNotes,
  };
};

/**
 * Retrieve saved reports from localStorage
 */
export const getStoredMonthlyReports = (): MonthlyReport[] => {
  try {
    const data = localStorage.getItem(STORAGE_KEY_REPORTS);
    if (!data) return [];
    const parsed = JSON.parse(data);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
};

/**
 * Save report into localStorage (replaces existing if same id)
 */
export const saveMonthlyReport = (report: MonthlyReport): MonthlyReport[] => {
  try {
    const existing = getStoredMonthlyReports();
    const filtered = existing.filter((r) => r.id !== report.id);
    const updated = [report, ...filtered];
    // Sort descending by year and month
    updated.sort((a, b) => {
      if (a.year !== b.year) return b.year - a.year;
      return b.month - a.month;
    });
    localStorage.setItem(STORAGE_KEY_REPORTS, JSON.stringify(updated));
    return updated;
  } catch (err) {
    console.error('Błąd zapisu raportu miesięcznego:', err);
    return [];
  }
};

/**
 * Delete a report from localStorage
 */
export const deleteMonthlyReport = (id: string): MonthlyReport[] => {
  try {
    const existing = getStoredMonthlyReports();
    const updated = existing.filter((r) => r.id !== id);
    localStorage.setItem(STORAGE_KEY_REPORTS, JSON.stringify(updated));
    return updated;
  } catch {
    return [];
  }
};

/**
 * Check and execute automated report generation:
 * Trigger condition:
 * - On the last day of the month at or after 23:50
 * - Catch-up: If previous month ended and report doesn't exist yet
 */
export const checkAndAutoGenerateReports = (
  tasks: Task[],
  costs: MonthlyCosts
): { generated: MonthlyReport | null; nextScheduled: string } => {
  const now = new Date();
  const curYear = now.getFullYear();
  const curMonth = now.getMonth() + 1; // 1 - 12
  const curDate = now.getDate();
  const curHours = now.getHours();
  const curMinutes = now.getMinutes();

  const daysInCurrentMonth = new Date(curYear, curMonth, 0).getDate();
  const nextScheduled = `${daysInCurrentMonth}.${String(curMonth).padStart(2, '0')}.${curYear} o 23:50`;

  const existingReports = getStoredMonthlyReports();
  let generatedReport: MonthlyReport | null = null;

  // 1. Condition: It is the last day of current month AND time >= 23:50
  const isLastDay = curDate === daysInCurrentMonth;
  const isPast2350 = curHours === 23 && curMinutes >= 50;

  const currentReportId = `report-${curYear}-${String(curMonth).padStart(2, '0')}`;
  const currentAlreadyExists = existingReports.some((r) => r.id === currentReportId);

  if (isLastDay && isPast2350 && !currentAlreadyExists) {
    const rep = generateMonthlyReport(curYear, curMonth, tasks, costs, true);
    saveMonthlyReport(rep);
    generatedReport = rep;
  }

  // 2. Catch-up condition: check previous month
  // If we are in the next month (e.g. 1st or later), make sure the previous month's report was generated!
  let prevYear = curYear;
  let prevMonth = curMonth - 1;
  if (prevMonth === 0) {
    prevMonth = 12;
    prevYear -= 1;
  }

  const prevReportId = `report-${prevYear}-${String(prevMonth).padStart(2, '0')}`;
  const prevAlreadyExists = existingReports.some((r) => r.id === prevReportId);

  // If previous month has ended and its report is missing, generate it automatically
  if (!prevAlreadyExists && !generatedReport) {
    // Only auto-generate if we have any tasks from that year/month
    const prevTasks = filterTasksForMonth(tasks, prevYear, prevMonth);
    if (prevTasks.length > 0) {
      const rep = generateMonthlyReport(prevYear, prevMonth, tasks, costs, true);
      saveMonthlyReport(rep);
      generatedReport = rep;
    }
  }

  return {
    generated: generatedReport,
    nextScheduled,
  };
};
