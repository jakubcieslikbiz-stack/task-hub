import React from 'react';
import type { MonthlyReport } from '../types';
import {
  X,
  Printer,
  Download,
  Calendar,
  TrendingUp,
  Receipt,
  DollarSign,
  Clock,
  Sparkles
} from 'lucide-react';

interface MonthlyReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: MonthlyReport | null;
}

export const MonthlyReportModal: React.FC<MonthlyReportModalProps> = ({
  isOpen,
  onClose,
  report,
}) => {
  if (!isOpen || !report) return null;

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadJson = () => {
    const jsonStr = JSON.stringify(report, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Raport_JC_Studio_${report.id}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const formattedDate = new Date(report.generatedAt).toLocaleString('pl-PL', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 overflow-y-auto bg-[#0c0907]/80 backdrop-blur-md">
      <div className="relative w-full max-w-3xl glass-panel rounded-3xl border border-[#3d2f24] p-6 sm:p-8 shadow-2xl space-y-6 my-auto text-[#f5ede4] max-h-[92vh] overflow-y-auto">
        {/* Modal Top Bar */}
        <div className="flex items-center justify-between pb-4 border-b border-[#2e231c]">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-[#d99b5a]/15 border border-[#d99b5a]/30 flex items-center justify-center text-[#d99b5a]">
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <span className="text-[10px] font-mono uppercase tracking-widest text-[#d99b5a] block">
                JC STUDIO • RAPORT ROZLICZENIOWY
              </span>
              <h2 className="text-xl font-light tracking-tight text-[#f5ede4]">
                Raport Miesięczny: {report.monthName}
              </h2>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="px-3.5 py-1.5 rounded-full bg-[#251b14] hover:bg-[#322319] text-[#9e8f82] hover:text-[#f5ede4] border border-[#382b20] text-xs font-medium flex items-center gap-1.5 transition-all active:scale-95"
              title="Drukuj lub zapisz do formatu PDF"
            >
              <Printer className="w-3.5 h-3.5 text-[#d99b5a]" />
              <span className="hidden sm:inline">Drukuj / PDF</span>
            </button>
            <button
              onClick={handleDownloadJson}
              className="p-2 rounded-xl text-[#9e8f82] hover:text-[#f5ede4] hover:bg-[#251b14] border border-transparent hover:border-[#382b20] transition-colors"
              title="Pobierz dane JSON"
            >
              <Download className="w-4 h-4" />
            </button>
            <button
              onClick={onClose}
              className="p-2 rounded-xl text-[#9e8f82] hover:text-[#f5ede4] hover:bg-[#251b14] transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Report Metadata Banner */}
        <div className="flex flex-wrap items-center justify-between gap-3 p-4 rounded-2xl bg-[#140f0c] border border-[#2e231c] text-xs">
          <div className="flex items-center gap-2 text-[#9e8f82]">
            <Calendar className="w-4 h-4 text-[#d99b5a]" />
            <span>Okres rozliczeniowy:</span>
            <strong className="text-[#f5ede4] font-mono">{report.period}</strong>
          </div>
          <div className="flex items-center gap-2">
            <span className="w-2 h-2 rounded-full bg-[#7ec29a]" />
            <span className="text-[#9e8f82]">Generowanie:</span>
            <span className="px-2.5 py-0.5 rounded-full bg-[#7ec29a]/15 text-[#9ee2b9] border border-[#7ec29a]/30 font-mono text-[11px]">
              {report.isAutoGenerated ? 'Automatycznie (23:50)' : 'Na żądanie (Podgląd)'}
            </span>
            <span className="text-[#7a6b5e] font-mono text-[11px] hidden sm:inline">
              • {formattedDate}
            </span>
          </div>
        </div>

        {/* Financial KPI Cards */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
          {/* Przychód zrealizowany */}
          <div className="p-4 rounded-2xl bg-[#140f0c] border border-[#2e231c]">
            <span className="text-[10px] font-mono uppercase text-[#9e8f82] flex items-center gap-1.5">
              <DollarSign className="w-3 h-3 text-[#7ec29a]" />
              Przychód zrealizowany
            </span>
            <div className="text-xl sm:text-2xl font-light text-[#7ec29a] font-mono mt-1">
              {report.financials.paidRevenue.toLocaleString('pl-PL')} zł
            </div>
            <div className="text-[10px] text-[#7a6b5e] mt-0.5">
              {report.metrics.paidCount} opłaconych zleceń
            </div>
          </div>

          {/* Oczekujące */}
          <div className="p-4 rounded-2xl bg-[#140f0c] border border-[#2e231c]">
            <span className="text-[10px] font-mono uppercase text-[#9e8f82] flex items-center gap-1.5">
              <Clock className="w-3 h-3 text-[#d99b5a]" />
              Oczekujące
            </span>
            <div className="text-xl sm:text-2xl font-light text-[#f5ede4] font-mono mt-1">
              {report.financials.pendingRevenue.toLocaleString('pl-PL')} zł
            </div>
            <div className="text-[10px] text-[#7a6b5e] mt-0.5">
              W toku / do zapłaty
            </div>
          </div>

          {/* Koszty stałe */}
          <div className="p-4 rounded-2xl bg-[#140f0c] border border-[#2e231c]">
            <span className="text-[10px] font-mono uppercase text-[#9e8f82] flex items-center gap-1.5">
              <Receipt className="w-3 h-3 text-[#e07a68]" />
              Koszty (ZUS + Podatek)
            </span>
            <div className="text-xl sm:text-2xl font-light text-[#e07a68] font-mono mt-1">
              {report.financials.totalCosts.toLocaleString('pl-PL')} zł
            </div>
            <div className="text-[10px] text-[#7a6b5e] mt-0.5 font-mono">
              ZUS {report.financials.zus} + PIT {report.financials.tax}
            </div>
          </div>

          {/* Zysk netto */}
          <div className="p-4 rounded-2xl bg-[#140f0c] border border-[#7ec29a]/30">
            <span className="text-[10px] font-mono uppercase text-[#7ec29a] flex items-center gap-1.5">
              <TrendingUp className="w-3 h-3 text-[#7ec29a]" />
              Zysk netto (Na czysto)
            </span>
            <div
              className={`text-xl sm:text-2xl font-semibold font-mono mt-1 ${
                report.financials.netProfit >= 0 ? 'text-[#7ec29a]' : 'text-[#e07a68]'
              }`}
            >
              {report.financials.netProfit >= 0 ? '+' : ''}
              {report.financials.netProfit.toLocaleString('pl-PL')} zł
            </div>
            <div className="text-[10px] text-[#9e8f82] mt-0.5">
              Marża: {report.financials.profitMargin}%
            </div>
          </div>
        </div>

        {/* Executive Summary */}
        {report.executiveNotes && (
          <div className="p-4 rounded-2xl bg-[#1a1410] border border-[#2e231c] text-xs text-[#d9cbbd] leading-relaxed">
            <span className="text-[10px] font-mono uppercase text-[#d99b5a] block mb-1">
              Podsumowanie wykonawcze
            </span>
            {report.executiveNotes}
          </div>
        )}

        {/* Orders Breakdown Table */}
        <div className="space-y-3">
          <div className="flex items-center justify-between text-xs">
            <span className="font-medium text-[#f5ede4]">
              Zestawienie zleceń w miesiącu ({report.orders.length})
            </span>
            <span className="text-[#9e8f82] font-mono text-[11px]">
              Skuteczność: <strong className="text-[#7ec29a]">{report.metrics.completionRate}%</strong>
            </span>
          </div>

          <div className="border border-[#2e231c] rounded-2xl overflow-hidden bg-[#140f0c]/60 max-h-[260px] overflow-y-auto">
            {report.orders.length === 0 ? (
              <div className="p-6 text-center text-xs text-[#7a6b5e]">
                Brak zarejestrowanych zleceń w tym miesiącu.
              </div>
            ) : (
              <table className="w-full text-left text-xs">
                <thead className="bg-[#1c1511] text-[10px] font-mono uppercase text-[#9e8f82] border-b border-[#2e231c]">
                  <tr>
                    <th className="py-2.5 px-3">Zlecenie</th>
                    <th className="py-2.5 px-3">Status</th>
                    <th className="py-2.5 px-3">Termin</th>
                    <th className="py-2.5 px-3 text-right">Wartość</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-[#261d17] text-xs">
                  {report.orders.map((o) => (
                    <tr key={o.id} className="hover:bg-[#1f1712]/50 transition-colors">
                      <td className="py-2.5 px-3 font-medium text-[#f5ede4]">{o.title}</td>
                      <td className="py-2.5 px-3">
                        <span
                          className={`inline-block px-2 py-0.5 rounded-full text-[10px] font-mono ${
                            o.status === 'paid'
                              ? 'bg-[#7ec29a]/15 text-[#9ee2b9] border border-[#7ec29a]/30'
                              : o.status === 'done'
                              ? 'bg-[#d99b5a]/15 text-[#f1c38e] border border-[#d99b5a]/30'
                              : 'bg-[#251b14] text-[#9e8f82]'
                          }`}
                        >
                          {o.status === 'paid' ? 'Opłacone' : o.status === 'done' ? 'Gotowe' : 'W toku'}
                        </span>
                      </td>
                      <td className="py-2.5 px-3 font-mono text-[#9e8f82] text-[11px]">
                        {o.dueDate || 'brak'}
                      </td>
                      <td className="py-2.5 px-3 text-right font-mono font-medium text-[#f5ede4]">
                        {o.price > 0 ? `${o.price.toLocaleString('pl-PL')} zł` : '—'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </div>
        </div>

        {/* Footer */}
        <div className="pt-3 border-t border-[#2e231c] flex items-center justify-between text-xs">
          <span className="text-[#7a6b5e] text-[11px] font-mono">
            JC Studio • ID raportu: {report.id}
          </span>
          <button
            onClick={onClose}
            className="px-5 py-2 rounded-full bg-[#f5ede4] hover:bg-white text-[#120e0a] text-xs font-semibold shadow-md transition-all active:scale-95"
          >
            Zamknij
          </button>
        </div>
      </div>
    </div>
  );
};
