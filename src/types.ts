export type Priority = 'low' | 'medium' | 'high' | 'urgent';

export type Status = 'todo' | 'in_progress' | 'done' | 'paid';

export interface Subtask {
  id: string;
  title: string;
  completed: boolean;
}

export interface Task {
  id: string;
  title: string;
  description?: string;
  price?: number;        // Kwota zlecenia w PLN
  startDate?: string;    // Data rozpoczęcia (YYYY-MM-DD)
  dueDate?: string;      // Termin / Deadline (YYYY-MM-DD)
  dueTime?: string;      // Godzina (np. "14:00")
  reminderTime?: string; // Czas przypomnienia (np. "godzinę przed")
  category: string;
  priority: Priority;
  status: Status;        // todo | in_progress | done | paid
  notes?: string;        // Uwagi do projektu
  remindByEmail?: boolean; // Czy wysłać/oznaczyć przypomnienie e-mail
  emailReminderSentAt?: string; // Data i czas faktycznego wysłania przypomnienia
  emailReminderScheduledAt?: string; // Data i czas ZAPLANOWANEGO wysłania (ISO)
  emailReminderId?: string; // Identyfikator zaplanowanego maila w Resend
  subtasks: Subtask[];
  createdAt: string;
  completedAt?: string;
}

export type ViewMode =
  | 'today'
  | 'all'
  | 'pomodoro'
  | 'timeline'
  | 'finances'
  | 'converter'
  | 'dwg_converter'
  | 'offers'
  | 'portfolio_manager';

export interface PortfolioProject {
  id: string;
  title: string;
  category: string;
  categoryLabel: string;
  description: string;
  imageUrl: string;
  client?: string;
  year?: string;
  tags: string[];
  featured?: boolean;
}

export interface Note {
  id: string;
  title: string;
  content: string;
  updatedAt: string;
}

export interface CostItem {
  id: string;
  name: string;
  cost: number;
  type: 'business' | 'private';
  date: string;
}

export interface MonthlyCosts {
  zus: number;
  tax: number;
}

export interface MonthlyReportOrder {
  id: string;
  title: string;
  price: number;
  status: Status;
  category: string;
  dueDate?: string;
  completedAt?: string;
}

export interface MonthlyReport {
  id: string; // np. "report-2026-11"
  year: number;
  month: number; // 1-12
  monthName: string; // np. "Listopad 2026"
  period: string; // np. "01.11.2026 – 30.11.2026"
  generatedAt: string; // ISO string
  isAutoGenerated: boolean;
  financials: {
    paidRevenue: number;
    pendingRevenue: number;
    totalValue: number;
    zus: number;
    tax: number;
    totalCosts: number;
    netProfit: number;
    profitMargin: number;
  };
  metrics: {
    totalTasks: number;
    paidCount: number;
    doneCount: number;
    inProgressCount: number;
    completionRate: number;
  };
  orders: MonthlyReportOrder[];
  executiveNotes?: string;
}
