export type Priority = 'low' | 'medium' | 'high' | 'urgent';

export type Status = 'todo' | 'in_progress' | 'done' | 'paid';

export type StickyNoteColor = 'honey' | 'mint' | 'lavender' | 'coral' | 'azure' | 'coffee';

export interface FixedBillItem {
  id: string;
  title: string;
  dueDayDescription: string;
  reminderDayDescription: string;
  dueDay: number; // 1-31, lub -1 dla ostatniego dnia miesiąca
  reminderDay: number; // 1-31, lub -1 dla ostatniego dnia miesiąca
  category: 'home' | 'utilities' | 'business' | 'finance' | 'other';
  iconName: 'Home' | 'Zap' | 'Receipt' | 'TrendingDown' | 'Landmark' | 'FileText' | 'PiggyBank';
  accountNumber?: string;
  defaultAmount?: number;
  notes?: string;
}

export interface MonthlyBillEntry {
  amount: number;
  paid: boolean;
  paidAt?: string;
  notes?: string;
}

export type MonthlyBillsData = Record<string, Record<string, MonthlyBillEntry>>;

export interface Subtask {
  id: string;
  title: string;
  completed: boolean;
}

export interface Task {
  id: string;
  title: string;
  description?: string;
  price?: number;        // Kwota zlecenia w PLN
  startDate?: string;    // Data rozpoczęcia (YYYY-MM-DD)
  dueDate?: string;      // Termin / Deadline (YYYY-MM-DD)
  dueTime?: string;      // Godzina (np. "14:00")
  reminderTime?: string; // Czas przypomnienia (np. "godzinę przed")
  category: string;
  priority: Priority;
  status: Status;        // todo | in_progress | done | paid
  isWaitingForFeedback?: boolean; // Czekam na uwagi od klienta (leci na dół listy w toku)
  notes?: string;        // Uwagi do projektu
  remindByEmail?: boolean; // Czy wysłać/oznaczyć przypomnienie e-mail
  emailReminderSentAt?: string; // Data i czas faktycznego wysłania przypomnienia
  emailReminderScheduledAt?: string; // Data i czas ZAPLANOWANEGO wysłania (ISO)
  emailReminderId?: string; // Identyfikator zaplanowanego maila w Resend
  subtasks: Subtask[];
  createdAt: string;
  completedAt?: string;
  stickyColor?: StickyNoteColor; // Kolor karteczki samoprzylepnej dla spraw osobistych
}

